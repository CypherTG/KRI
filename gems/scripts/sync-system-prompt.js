const fs = require('fs');
const path = require('path');

const sourcePath = path.resolve(__dirname, '..', '..', 'system_prompt.tsx');
const targetTsxPath = path.resolve(__dirname, '..', 'system_prompt.tsx');
const targetJsPath = path.resolve(__dirname, '..', 'system_prompt.js');

if (!fs.existsSync(sourcePath)) {
  throw new Error(`Source system prompt not found: ${sourcePath}`);
}

const sourceText = fs.readFileSync(sourcePath, 'utf8');
const marker = 'export const AIROS_SYSTEM_PROMPT = `';
const start = sourceText.indexOf(marker);
if (start < 0) {
  throw new Error(`Could not locate AIROS_SYSTEM_PROMPT in ${sourcePath}`);
}
const bodyStart = start + marker.length;
let bodyEnd = sourceText.indexOf('\n\n/**', bodyStart);
if (bodyEnd < 0) {
  bodyEnd = sourceText.indexOf('\r\n\r\n/**', bodyStart);
}
if (bodyEnd < 0) {
  throw new Error(`Could not locate the end of AIROS_SYSTEM_PROMPT in ${sourcePath}`);
}

const prompt = sourceText.slice(bodyStart, bodyEnd);

fs.copyFileSync(sourcePath, targetTsxPath);
fs.writeFileSync(
  targetJsPath,
  [
    '// Auto-generated from ../system_prompt.tsx',
    '// Do not edit this file directly.',
    `exports.AIROS_SYSTEM_PROMPT = ${JSON.stringify(prompt)};`,
    '',
  ].join('\n'),
  'utf8',
);

console.log(`Synced system prompt: ${sourcePath} -> ${targetTsxPath} and ${targetJsPath}`);
